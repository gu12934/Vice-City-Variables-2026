#!/usr/bin/env bash
# Export the latest successful pipeline run from the running Postgres container into db/seed.sql.gz.
# Postgres loads that file on first start (empty volume), so a fresh clone opens with results
# already in place and nobody has to run the pipeline.
#
# Usage (from the app/ folder, with the stack running):  bash db/export_seed.sh
set -euo pipefail
cd "$(dirname "$0")/.."

psql_q() { docker compose exec -T postgres psql -U app -d app -At -c "$1"; }

RUN_ID=$(psql_q "SELECT run_id FROM pipeline_runs WHERE status='success' ORDER BY finished_at DESC LIMIT 1")
[ -n "$RUN_ID" ] || { echo "No successful run found. Run the pipeline first." >&2; exit 1; }
echo "Exporting run $RUN_ID"

dump() {  # dump <table> <select-columns>
  echo "COPY $1 FROM stdin;"
  psql_q "COPY (SELECT $2 FROM $1 WHERE run_id = '$RUN_ID') TO STDOUT"
  printf '\\.\n\n'
}

{
  echo "-- Seed: results of pipeline run $RUN_ID (generated by db/export_seed.sh)"
  echo "\\connect app"
  echo "BEGIN;"
  # mlflow_run_id is cleared: a fresh MLflow volume does not contain that run.
  dump pipeline_runs "run_id, status, current_step, steps, started_at, finished_at, NULL::text, error, summary"
  dump chart_data "*"
  dump well_scores "*"
  dump well_reasons "*"
  dump well_detail "*"
  echo "COMMIT;"
} | gzip -9 > db/seed.sql.gz

ls -lh db/seed.sql.gz
